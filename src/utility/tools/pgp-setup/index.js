/**
 * Read the PGP configuration file
 * @param {string} projectRoot - Project root directory
 * @returns {object|null} Parsed config or null if not found
 */
export function readPgpConfig(projectRoot = process.cwd()) {
  const configPath = path.join(projectRoot, PGP_CONFIG_PATH);

  if (!fs.existsSync(configPath)) {
    return null;
  }

  try {
    const content = fs.readFileSync(configPath, 'utf8');
    // Simple YAML parsing for our config format
    const config = {};
    const lines = content.split('\n');

    for (const line of lines) {
      const trimmed = line.trim();
      if (trimmed && !trimmed.startsWith('#')) {
        const colonIndex = trimmed.indexOf(':');
        if (colonIndex > 0) {
          const key = trimmed.slice(0, colonIndex).trim();
          let value = trimmed.slice(colonIndex + 1).trim();
          // Remove quotes if present
          if ((value.startsWith("'") && value.endsWith("'")) ||
              (value.startsWith('"') && value.endsWith('"'))) {
            value = value.slice(1, -1);
          }
          config[key] = value;
        }
      }
    }

    return config;
  } catch (error) {
    return null;
  }
}

/**
 * Write the PGP configuration file
 * @param {object} config - Configuration to write
 * @param {string} projectRoot - Project root directory
 * @returns {{success: boolean, path: string, error: string|null}}
 */
export function writePgpConfig(config, projectRoot = process.cwd()) {
  const configPath = path.join(projectRoot, PGP_CONFIG_PATH);
  const configDir = path.dirname(configPath);

  try {
    // Ensure directory exists
    if (!fs.existsSync(configDir)) {
      fs.mkdirSync(configDir, { recursive: true });
    }

    // Generate YAML content
    const lines = [
      '# BMAD PGP Configuration',
      '# Generated by PGP Setup Wizard v' + VERSION,
      '# Last updated: ' + new Date().toISOString(),
      ''
    ];

    for (const [key, value] of Object.entries(config)) {
      if (Array.isArray(value)) {
        lines.push(key + ':');
        for (const item of value) {
          lines.push('  - ' + item);
        }
      } else {
        lines.push(key + ': ' + (typeof value === 'string' ? "'" + value + "'" : value));
      }
    }

    fs.writeFileSync(configPath, lines.join('\n') + '\n', 'utf8');

    return { success: true, path: configPath, error: null };
  } catch (error) {
    return { success: false, path: configPath, error: error.message };
  }
}

