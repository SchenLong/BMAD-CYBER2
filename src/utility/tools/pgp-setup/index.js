/**
 * Run the PGP setup wizard
 * @param {Object} options - Setup options
 * @param {string} [options.projectRoot] - Project root directory
 * @param {boolean} [options.generate] - Skip to key generation
 * @param {boolean} [options.sign] - Skip to config signing
 * @param {boolean} [options.status] - Show status only
 * @param {boolean} [options.silent] - Suppress banner output
 * @returns {Promise<{success: boolean, action: string, result: object|null, error: string|null}>}
 */
export async function runPgpSetup(options = {}) {
  const {
    projectRoot = process.cwd(),
    generate = false,
    sign = false,
    status = false,
    silent = false
  } = options;

  // Display banner unless silent mode
  if (!silent) {
    displayBanner();
  }

  // Step 1: Check GPG capability
  console.log(chalk.dim('Checking GPG availability...\n'));
  const gpgStatus = await checkGpgCapability();

  if (!gpgStatus.available) {
    console.log(chalk.red('GPG is not available on this system.\n'));
    console.log(chalk.yellow('Installation Instructions:'));
    console.log(getInstallInstructions());
    console.log();
    return {
      success: false,
      action: 'check',
      result: gpgStatus,
      error: 'GPG not available'
    };
  }

  console.log(chalk.green(`GPG found: v${gpgStatus.version} at ${gpgStatus.path}\n`));

  // Step 2: Check current key status
  const keyStatus = showCurrentKeyStatus(projectRoot);

  // Handle status-only mode
  if (status) {
    if (keyStatus.hasKey) {
      await showSignedFilesStatus(projectRoot);
    }
    return {
      success: true,
      action: 'status',
      result: keyStatus,
      error: null
    };
  }

  // Handle direct sign mode
  if (sign) {
    if (!keyStatus.hasKey) {
      console.log(chalk.red('No PGP key found. Generate a key first.\n'));
      return {
        success: false,
        action: 'sign',
        result: null,
        error: 'No key available for signing'
      };
    }

    console.log(chalk.dim('\nSigning configuration files...\n'));
    const signResult = await signAllConfigs({
      fingerprint: keyStatus.config.fingerprint,
      projectRoot
    });

    if (signResult.success) {
      console.log(chalk.green(`Signed ${signResult.signedFiles.length} file(s) successfully.\n`));
      for (const filePath of signResult.signedFiles) {
        const relativePath = path.relative(projectRoot, filePath);
        console.log(`  ${chalk.cyan('*')} ${relativePath}`);
      }
      console.log();
    } else {
      console.log(chalk.red(`Failed to sign files: ${signResult.error}\n`));
    }

    return {
      success: signResult.success,
      action: 'sign',
      result: signResult,
      error: signResult.error
    };
  }

  // Handle direct generate mode
  if (generate) {
    if (keyStatus.hasKey) {
      const shouldReplace = await confirmReplaceKey();
      if (!shouldReplace) {
        console.log(chalk.yellow('\nKey generation cancelled.\n'));
        return {
          success: true,
          action: 'cancelled',
          result: null,
          error: null
        };
      }
    }

    return await performKeyGeneration(projectRoot);
  }

  // Interactive mode
  if (keyStatus.hasKey) {
    const action = await promptForAction();

    switch (action) {
      case 'view':
        await showSignedFilesStatus(projectRoot);
        return { success: true, action: 'view', result: keyStatus, error: null };

      case 'sign':
        console.log(chalk.dim('\nSigning configuration files...\n'));
        const signResult = await signAllConfigs({
          fingerprint: keyStatus.config.fingerprint,
          projectRoot
        });

        if (signResult.success) {
          console.log(chalk.green(`Signed ${signResult.signedFiles.length} file(s) successfully.\n`));
        }

        return {
          success: signResult.success,
          action: 'sign',
          result: signResult,
          error: signResult.error
        };

      case 'generate':
        const shouldReplace = await confirmReplaceKey();
        if (!shouldReplace) {
          console.log(chalk.yellow('\nKey generation cancelled.\n'));
          return { success: true, action: 'cancelled', result: null, error: null };
        }
        return await performKeyGeneration(projectRoot);

      case 'exit':
      default:
        console.log(chalk.dim('\nExiting PGP setup.\n'));
        return { success: true, action: 'exit', result: null, error: null };
    }
  } else {
    // No key exists, offer to generate
    const shouldGenerate = await confirmKeyGeneration();
    if (!shouldGenerate) {
      console.log(chalk.yellow('\nKey generation skipped.\n'));
      return { success: true, action: 'skipped', result: null, error: null };
    }

    return await performKeyGeneration(projectRoot);
  }
}

/**
 * Perform key generation and export
 * @param {string} projectRoot - Project root directory
 * @returns {Promise<object>} Generation result
 */
async function performKeyGeneration(projectRoot) {
  console.log(chalk.dim('\nStarting key generation...\n'));

  // Generate the key
  const genResult = await runKeyGeneration({ projectRoot });

  if (!genResult.success) {
    console.log(chalk.red(`Key generation failed: ${genResult.error}\n`));
    return {
      success: false,
      action: 'generate',
      result: genResult,
      error: genResult.error
    };
  }

  console.log(chalk.green('Key generated successfully!\n'));
  console.log(`  Fingerprint: ${chalk.cyan(genResult.fingerprint)}`);
  console.log(`  Key ID:      ${chalk.cyan(genResult.keyId)}`);
  console.log(`  Name:        ${genResult.name}`);
  console.log(`  Email:       ${genResult.email}\n`);

  // Export keys
  console.log(chalk.dim('Exporting public key...\n'));
  const exportResult = await exportKeys(genResult.fingerprint, projectRoot, { silent: true });

  if (exportResult.success) {
    console.log(chalk.green(`Public key exported to: ${exportResult.publicKeyPath}\n`));
  }

  // Save configuration
  const configResult = writePgpConfig({
    fingerprint: genResult.fingerprint,
    key_id: genResult.keyId,
    user_name: genResult.name,
    email: genResult.email,
    created_at: genResult.createdAt,
    public_key_path: exportResult.publicKeyPath
  }, projectRoot);

  if (configResult.success) {
    console.log(chalk.green(`Configuration saved to: ${configResult.path}\n`));
  }

  // Offer to sign configs
  const signNow = await confirm({
    message: 'Would you like to sign configuration files now?',
    initialValue: true
  });

  if (signNow) {
    console.log(chalk.dim('\nSigning configuration files...\n'));
    const signResult = await signAllConfigs({
      fingerprint: genResult.fingerprint,
      projectRoot
    });

    if (signResult.success) {
      console.log(chalk.green(`Signed ${signResult.signedFiles.length} file(s) successfully.\n`));
    }
  }

  console.log(chalk.bold.green('\nPGP setup complete!\n'));

  return {
    success: true,
    action: 'generate',
    result: {
      generation: genResult,
      export: exportResult,
      config: configResult
    },
    error: null
  };
}

