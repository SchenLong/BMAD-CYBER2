/**
 * Show current PGP key status
 * @param {string} projectRoot - Project root directory
 * @returns {object} Status information
 */
export function showCurrentKeyStatus(projectRoot = process.cwd()) {
  console.log(chalk.bold('\nPGP Key Status:\n'));

  const config = readPgpConfig(projectRoot);

  if (!config || !config.fingerprint) {
    console.log(chalk.yellow('  No PGP key configured.'));
    console.log(chalk.dim('  Run pgp:setup to generate a new key.\n'));
    return { hasKey: false, config: null };
  }

  // Display key information
  console.log(chalk.green('  Key configured:'));
  console.log('    Fingerprint: ' + chalk.cyan(config.fingerprint || 'N/A'));

  if (config.key_id) {
    console.log('    Key ID:      ' + chalk.cyan(config.key_id));
  }
  if (config.user_name) {
    console.log('    User:        ' + chalk.cyan(config.user_name));
  }
  if (config.email) {
    console.log('    Email:       ' + chalk.cyan(config.email));
  }
  if (config.created_at) {
    console.log('    Created:     ' + chalk.dim(config.created_at));
  }

  console.log();
  return { hasKey: true, config };
}

/**
 * Show signed files status
 * @param {string} projectRoot - Project root directory
 */
export async function showSignedFilesStatus(projectRoot = process.cwd()) {
  console.log(chalk.bold('Signed Files:\n'));

  const signedFiles = await getSignedFiles(projectRoot);

  if (signedFiles.length === 0) {
    console.log(chalk.yellow('  No signed configuration files found.'));
    console.log(chalk.dim('  Use --sign to sign configuration files.\n'));
    return;
  }

  console.log(chalk.green('  ' + signedFiles.length + ' file(s) signed:\n'));
  for (const filePath of signedFiles) {
    const relativePath = path.relative(projectRoot, filePath);
    console.log('    ' + chalk.cyan('*') + ' ' + relativePath);
  }
  console.log();
}

